// 2. Registration
//= = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = =

/*
 * Tag a path as a constraint driver and return its ID.
 *
 * An object that already has an ID keeps it and keeps its kind. That second
 * part matters: a circle generated by a tangent-circle constraint is a
 * perfectly good driver for the next constraint, and an earlier version
 * stamped kind=circle over it, silently destroying the constraint that built
 * it. Only a bare reference is promoted.
 */
function conRegisterCircle(path) {
    var rec = metaRead(path);
    if (rec && rec.id) {
        if (rec.kind === "ref") {
            rec.kind = "circle";
            metaWrite(path, rec);
            conInvalidate();
        }
        return rec.id;
    }
    var id = metaNewId("c");
    metaPatch(path, { kind: "circle", id: id });
    conInvalidate();
    return id;
}

function conRegisterRef(path) {
    var rec = metaRead(path);
    if (rec && rec.id) { return rec.id; }
    var id = metaNewId("p");
    metaPatch(path, { kind: "ref", id: id });
    conInvalidate();
    return id;
}

/*
 * A container that can take a new sibling. Compound paths accept pathItems.add
 * but a new member would join the compound and inherit its even-odd fill, so
 * step out to the compound's own parent instead.
 */
function conContainerFor(item) {
    var p;
    try { p = item.parent; } catch (e) { return app.activeDocument; }
    try {
        if (p && p.typename === "CompoundPathItem") { return p.parent; }
    } catch (e2) {}
    return p || app.activeDocument;
}

function conNewPath(sibling, pts, closed) {
    var parent = conContainerFor(sibling);
    var p = parent.pathItems.add();
    writePath(p, pts, closed);
    if (typeof closed === "boolean") { p.closed = closed; }
    return p;
}

