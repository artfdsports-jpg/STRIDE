/*
 * The headline operation: take two circles and join them along their common
 * tangents, locked. Style "belt" gives the single closed pulley outline;
 * "lines" gives the two straight tangents as separate paths; "line" gives one.
 */
CMD.tanConnect = function (o) {
    var got = twoCircles();
    if (got.err) { return got.err; }

    var style = chStr(o.style, "belt");
    var crossed = chBool(o.crossed, false);
    var idA = conRegisterCircle(got.pathA);
    var idB = conRegisterCircle(got.pathB);

    var made = [], sides, i, side, pts, np;

    if (style === "belt") {
        pts = beltOutline(got.A.c, got.A.r, got.B.c, got.B.r, crossed);
        if (!pts) {
            return crossed
                ? "These circles overlap, so they have no crossed tangent. Move them apart or use the open belt."
                : "One circle is entirely inside the other, so they share no tangent.";
        }
        np = conNewPath(got.pathA, pts, true);
        styleFrom(np, got.pathA, true);
        metaWrite(np, { kind: "tanlink", id: metaNewId("t"), a: idA, b: idB, style: "belt", crossed: crossed });
        made.push(np);
    } else {
        sides = (style === "line") ? [chNum(o.side, 1)] : [1, -1];
        for (i = 0; i < sides.length; i++) {
            side = sides[i];
            pts = tangentSegment(got.A.c, got.A.r, got.B.c, got.B.r, crossed, side);
            if (!pts) { continue; }
            np = conNewPath(got.pathA, pts, false);
            styleFrom(np, got.pathA, false);
            metaWrite(np, { kind: "tanlink", id: metaNewId("t"), a: idA, b: idB, style: "line", crossed: crossed, side: side });
            made.push(np);
        }
        if (!made.length) {
            return crossed
                ? "These circles overlap, so they have no crossed tangent."
                : "One circle is entirely inside the other, so they share no tangent.";
        }
    }

    conInvalidate();
    app.activeDocument.selection = made;
    return "Locked " + made.length + " " + (style === "belt" ? "belt" : "tangent") +
           (made.length === 1 ? "" : "s") + " to both circles. Move or scale either circle and it follows.";
};

/* A new circle of a given radius, tangent to the two selected circles. */
CMD.tanCircleAdd = function (o) {
    var got = twoCircles();
    if (got.err) { return got.err; }

    var r = chNum(o.radius, 50);
    if (r <= 0) { return "Radius must be greater than zero."; }
    var mode = chStr(o.mode, "ee");
    var pick = chNum(o.pick, 0);

    var sols = tangentCircle(got.A.c, got.A.r, got.B.c, got.B.r, r, mode);
    if (!sols.length) {
        return "No circle of radius " + r + " can touch both. Try a larger radius, or a different inside/outside mode.";
    }
    var s = sols[pick] || sols[0];

    var idA = conRegisterCircle(got.pathA);
    var idB = conRegisterCircle(got.pathB);
    var np = conNewPath(got.pathA, arcPoints(s.c, s.r, 0, 0, true), true);
    styleFrom(np, got.pathA, false);
    metaWrite(np, {
        kind: "tancircle", id: metaNewId("k"), a: idA, b: idB,
        r: r, mode: mode, pick: pick, cx: s.c[0], cy: s.c[1]
    });

    conInvalidate();
    app.activeDocument.selection = [np];
    return "Tangent circle placed and locked to both drivers.";
};

/*
 * Tangent from a selected anchor to a circle. Select the circle and a path with
 * exactly one anchor selected; the line stays attached to that anchor.
 */
CMD.tanFromPoint = function (o) {
    var paths = selectedPaths();
    if (paths.length !== 2) { return "Select a circle, plus one path with a single anchor selected."; }

    var i, c, circlePathIdx = -1;
    for (i = 0; i < 2; i++) {
        c = circleOfPath(paths[i]);
        if (c && c.ok) { circlePathIdx = i; break; }
    }
    if (circlePathIdx < 0) { return "Neither selected path is a circle."; }

    var circPath = paths[circlePathIdx];
    var srcPath = paths[1 - circlePathIdx];
    var C = circleOfPath(circPath);

    var pts = readPath(srcPath), idx = -1, n = 0;
    for (i = 0; i < pts.length; i++) { if (pts[i].sel) { idx = i; n++; } }
    if (n !== 1) { return "Select exactly one anchor on the other path. Found " + n + "."; }

    var origin = pts[idx].a;
    var t = tangentsFromPoint(origin, C.c, C.r);
    if (!t.length) { return "That point is inside the circle, so it has no tangent to it."; }

    var side = chNum(o.side, 1), hit = t[0];
    for (i = 0; i < t.length; i++) { if (t[i].side === side) { hit = t[i]; } }

    var idC = conRegisterCircle(circPath);
    var idS = conRegisterRef(srcPath);
    var np = conNewPath(circPath, linePoints(origin, hit.p), false);
    styleFrom(np, circPath, false);
    metaWrite(np, {
        kind: "tanline", id: metaNewId("l"), a: idC, from: idS, fromIndex: idx,
        side: side, px: origin[0], py: origin[1]
    });

    conInvalidate();
    app.activeDocument.selection = [np];
    return "Tangent locked to the circle and to anchor " + (idx + 1) + ".";
};

/* Lock the selected anchors to tangent continuity. */
CMD.lockTangent = function () {
    var paths = selectedPaths(), i, j, pts, idx, rec, nPts = 0, nPaths = 0;
    if (!paths.length) { return "Select the anchors to lock."; }

    for (i = 0; i < paths.length; i++) {
        pts = readPath(paths[i]);
        idx = [];
        for (j = 0; j < pts.length; j++) { if (pts[j].sel) { idx.push(j); } }
        if (!idx.length) { continue; }

        rec = metaRead(paths[i]) || {};
        if (!rec.kind) { rec.kind = "ref"; }
        if (!rec.id) { rec.id = metaNewId("g"); }
        rec.locks = metaJoinNums(conMergeLocks(metaSplitNums(metaS(rec, "locks", "")), idx));
        metaWrite(paths[i], rec);
        nPts += idx.length;
        nPaths++;
    }
    if (!nPts) { return "No anchors selected. Use the Direct Selection tool first."; }

    conInvalidate();
    conSolveAll(true);
    return "Locked " + nPts + " anchor" + (nPts === 1 ? "" : "s") + " across " + nPaths +
           " path" + (nPaths === 1 ? "" : "s") + " to tangent continuity.";
};

function conMergeLocks(existing, add) {
    var out = [], seen = {}, i;
    for (i = 0; i < existing.length; i++) {
        if (!seen[existing[i]]) { seen[existing[i]] = true; out.push(existing[i]); }
    }
    for (i = 0; i < add.length; i++) {
        if (!seen[add[i]]) { seen[add[i]] = true; out.push(add[i]); }
    }
    return out;
}

/*
 * With anchors selected, release just those. With only whole objects selected,
 * release every lock on them. Only the locks field is touched: a path that is
 * also a tangent link keeps being one.
 */
CMD.unlockTangent = function () {
    var paths = selectedPaths(), i, j, pts, rec, locks, keep, n = 0, anySel;
    for (i = 0; i < paths.length; i++) {
        rec = metaRead(paths[i]);
        if (!rec || !rec.locks) { continue; }
        pts = readPath(paths[i]);
        locks = metaSplitNums(metaS(rec, "locks", ""));
        anySel = false;
        for (j = 0; j < pts.length; j++) { if (pts[j].sel) { anySel = true; break; } }

        keep = [];
        for (j = 0; j < locks.length; j++) {
            if (!anySel || (locks[j] >= 0 && locks[j] < pts.length && pts[locks[j]].sel)) { n++; }
            else { keep.push(locks[j]); }
        }
        if (keep.length) { rec.locks = metaJoinNums(keep); }
        else { delete rec.locks; }
        metaWrite(paths[i], rec);
    }
    conInvalidate();
    return n ? ("Released " + n + " tangent lock" + (n === 1 ? "" : "s") + ".")
             : "Nothing locked in the selection.";
};

/*
 * Weld two anchors on two different paths. The first selected path leads; the
 * second follows it. g1 also matches the tangent direction across the join.
 */
CMD.weldPoints = function (o) {
    var paths = selectedPaths();
    if (paths.length !== 2) { return "Select two paths with one anchor selected on each."; }

    var a = readPath(paths[0]), b = readPath(paths[1]);
    var ai = conSoleSelected(a), bi = conSoleSelected(b);
    if (ai < 0) { return "Select exactly one anchor on the first path."; }
    if (bi < 0) { return "Select exactly one anchor on the second path."; }

    var idA = conRegisterRef(paths[0]);
    conRegisterRef(paths[1]);

    // The record lives on the follower, because that is the path the solve
    // rewrites, and it merges into whatever role that path already has.
    var g1 = chBool(o.g1, true);
    var mode = chStr(o.mode, "shape");
    var rec = metaRead(paths[1]) || { kind: "ref", id: metaNewId("w") };
    rec.weldTo = idA;
    rec.weldTheirs = ai;
    rec.weldMine = bi;
    rec.weldG1 = g1;
    rec.weldMode = mode;
    metaWrite(paths[1], rec);

    conInvalidate();
    conSolveAll(true);
    return "Welded anchor " + (bi + 1) + " to anchor " + (ai + 1) +
           (g1 ? " with matched tangents. " : ". ") +
           (mode === "point" ? "Only that anchor follows." : "The whole second path follows.");
};

/* Break the weld on the selected paths, leaving the geometry where it is. */
CMD.unweld = function () {
    var paths = selectedPaths(), i, rec, n = 0;
    for (i = 0; i < paths.length; i++) {
        rec = metaRead(paths[i]);
        if (!rec || !rec.weldTo) { continue; }
        delete rec.weldTo;
        delete rec.weldTheirs;
        delete rec.weldMine;
        delete rec.weldG1;
        delete rec.weldMode;
        metaWrite(paths[i], rec);
        n++;
    }
    conInvalidate();
    return n ? ("Broke " + n + " weld" + (n === 1 ? "" : "s") + ".") : "Nothing welded in the selection.";
};

function conSoleSelected(pts) {
    var i, idx = -1, n = 0;
    for (i = 0; i < pts.length; i++) { if (pts[i].sel) { idx = i; n++; } }
    return (n === 1) ? idx : -1;
}

/* Re-solve everything now. */
CMD.solveAll = function () {
    var r = conSolveAll(true);
    if (!r.total) { return "Nothing is locked in this document."; }
    var msg = "Solved " + r.ok + " of " + r.total + ".";
    if (r.impossible) { msg += " " + r.impossible + " cannot be built at the current positions."; }
    if (r.broken) { msg += " " + r.broken + " lost a driver."; }
    return msg;
};

/*
 * The auto-sync probe. Returns "hash|count" and, when the hash has moved since
 * the caller last saw it, re-solves first. Keeping the compare on this side of
 * the bridge means the panel does one small evalScript per tick instead of
 * pulling the whole document state across.
 */
CMD.syncProbe = function (o) {
    var reg = conRegistry(false);
    if (!reg.links.length && !conHasLocks(reg)) { return "idle|0|0"; }

    var h = conStateHash(reg);
    var prev = chStr(o.hash, "");
    if (h === prev) { return "same|" + reg.count + "|0"; }

    var r = conSolveAll(false);
    // Solving moves dependent geometry, so the post-solve hash is the one to
    // compare against next tick. Without this the loop re-solves forever.
    var h2 = conStateHash(conRegistry(false));
    return "solved|" + r.ok + "|" + r.broken + "|" + h2;
};

function conHasLocks(reg) {
    var i;
    for (i = 0; i < reg.list.length; i++) {
        if (reg.list[i].rec.locks || reg.list[i].rec.weldTo) { return true; }
    }
    return false;
}

/* Current hash without solving, for the panel's first tick. */
CMD.syncHash = function () {
    return conStateHash(conRegistry(true));
};

/* Drop the constraint records on the selection, leaving ordinary artwork. */
CMD.releaseSelection = function () {
    var paths = selectedPaths(), i, n = 0;
    for (i = 0; i < paths.length; i++) {
        if (metaClear(paths[i])) { n++; }
    }
    conInvalidate();
    return n ? ("Released " + n + " object" + (n === 1 ? "" : "s") + ". They are plain paths now.")
             : "Nothing in the selection was locked.";
};

/* Select whatever drives the current selection, so you can see the chain. */
CMD.selectDrivers = function () {
    var reg = conRegistry(true);
    var paths = selectedPaths(), i, rec, out = [], e, refs, j;
    for (i = 0; i < paths.length; i++) {
        rec = metaRead(paths[i]);
        if (!rec) { continue; }
        refs = [rec.a, rec.b, rec.from];
        for (j = 0; j < refs.length; j++) {
            if (!refs[j]) { continue; }
            e = metaGet(reg, refs[j]);
            if (e && metaAlive(e)) { out.push(e.item); }
        }
    }
    if (!out.length) { return "The selection has no drivers."; }
    app.activeDocument.selection = out;
    return "Selected " + out.length + " driver" + (out.length === 1 ? "" : "s") + ".";
};

/* Panel readout: what is locked in this document, and is any of it broken. */
CMD.constraintsInfo = function () {
    var reg = conRegistry(true);
    var i, e, links = 0, circles = 0, locks = 0, welds = 0, broken = 0;
    for (i = 0; i < reg.list.length; i++) {
        e = reg.list[i];
        if (e.kind === "tanlink" || e.kind === "tanline" || e.kind === "tancircle") {
            links++;
            if (!conCircleOf(reg, e.rec.a) || (e.rec.b && !conCircleOf(reg, e.rec.b))) { broken++; }
        } else if (e.kind === "circle") { circles++; }
        if (e.rec.locks) { locks += metaSplitNums(metaS(e.rec, "locks", "")).length; }
        if (e.rec.weldTo) {
            welds++;
            if (!metaGet(reg, e.rec.weldTo)) { broken++; }
        }
    }
    return links + "|" + circles + "|" + locks + "|" + welds + "|" + broken;
};
