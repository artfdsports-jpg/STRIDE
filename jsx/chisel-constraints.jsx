/*
 * Resolve a driver reference to a live circle. Returns null when the driver was
 * deleted or has stopped being a circle, which the caller must treat as a
 * broken constraint rather than an error - deleting one of two circles is a
 * perfectly reasonable thing for a user to do.
 */
function conCircleOf(reg, id) {
    var e = metaGet(reg, id);
    if (!e || !metaAlive(e)) { return null; }
    var c;
    try { c = circleOfPath(e.item); } catch (err) { return null; }
    if (!c) { return null; }
    return c;
}

/* Rebuild one link. Returns "ok", "broken", or "impossible". */
function conSolveLink(reg, entry) {
    var rec = entry.rec;
    var A = conCircleOf(reg, rec.a);
    var B = conCircleOf(reg, rec.b);
    if (!A || !B) { return "broken"; }

    var crossed = metaB(rec, "crossed", false);
    var style = metaS(rec, "style", "belt");
    var side = metaN(rec, "side", 1);
    var pts = null, closed = true;

    if (style === "belt") {
        pts = beltOutline(A.c, A.r, B.c, B.r, crossed);
        closed = true;
    } else {
        pts = tangentSegment(A.c, A.r, B.c, B.r, crossed, side);
        closed = false;
    }
    if (!pts) { return "impossible"; }

    writePath(entry.item, pts, closed);
    return "ok";
}

/* Rebuild a circle that is defined as tangent to two others. */
function conSolveTanCircle(reg, entry) {
    var rec = entry.rec;
    var A = conCircleOf(reg, rec.a);
    var B = conCircleOf(reg, rec.b);
    if (!A || !B) { return "broken"; }

    var r = metaN(rec, "r", 50);
    var mode = metaS(rec, "mode", "ee");
    var pick = metaN(rec, "pick", 0);
    var sols = tangentCircle(A.c, A.r, B.c, B.r, r, mode);
    if (!sols.length) { return "impossible"; }
    var s = sols[pick] || sols[0];

    // Deliberately not writing the solved centre back into the record. It would
    // be a tag write on every solve, and the value is derived anyway.
    writePath(entry.item, arcPoints(s.c, s.r, 0, 0, true), true);
    return "ok";
}

/*
 * A tangent line running from a fixed anchor on another path to a circle. The
 * anchor is referenced by path ID and point index rather than copied, so
 * dragging that point drags the tangent with it.
 */
function conSolveTanLine(reg, entry) {
    var rec = entry.rec;
    var C = conCircleOf(reg, rec.a);
    if (!C) { return "broken"; }

    var origin = null;
    var src = metaGet(reg, metaS(rec, "from", ""));
    if (src && metaAlive(src)) {
        var pts = readPath(src.item);
        var idx = metaN(rec, "fromIndex", 0);
        if (idx >= 0 && idx < pts.length) { origin = pts[idx].a; }
    }
    if (!origin) { origin = [metaN(rec, "px", 0), metaN(rec, "py", 0)]; }

    var t = tangentsFromPoint(origin, C.c, C.r);
    if (!t.length) { return "impossible"; }
    var side = metaN(rec, "side", 1), i, hit = t[0];
    for (i = 0; i < t.length; i++) { if (t[i].side === side) { hit = t[i]; } }

    writePath(entry.item, linePoints(origin, hit.p), false);
    return "ok";
}

/*
 * Tangent continuity lock. The two handles at a locked anchor are forced
 * collinear on every solve, each keeping its own length, using the line from
 * the in handle to the out handle as the shared direction. That is exactly what
 * a smooth point means, and re-asserting it after every edit is what stops the
 * usual slow decay of a curve that was smooth when you drew it.
 */
function conSolveG1(entry) {
    var path = entry.item;
    var pts, idx, i, k, p, dir, lenL, lenR, nl, nr, changed = 0;
    try { pts = readPath(path); } catch (e) { return "broken"; }

    idx = metaSplitNums(metaS(entry.rec, "locks", ""));
    if (!idx.length) { return "ok"; }

    for (i = 0; i < idx.length; i++) {
        k = idx[i];
        if (k < 0 || k >= pts.length) { continue; }
        p = pts[k];
        lenL = vDist(p.a, p.l);
        lenR = vDist(p.a, p.r);
        if (lenL < 1e-9 && lenR < 1e-9) { continue; }

        dir = vSub(p.r, p.l);
        if (vLen(dir) < 1e-9) {
            // Both handles retracted onto one side: fall back to whichever
            // handle still has length, so the lock cannot invent a direction.
            dir = (lenR > lenL) ? vSub(p.r, p.a) : vSub(p.a, p.l);
        }
        if (vLen(dir) < 1e-9) { continue; }
        dir = vNorm(dir);

        nl = vSub(p.a, vMul(dir, lenL));
        nr = vAdd(p.a, vMul(dir, lenR));
        // Compare before assigning. A lock that is already satisfied must be a
        // true no-op, or the sync loop sees the rewrite as a change and solves
        // again on every tick.
        if (vDist(nl, p.l) < 1e-9 && vDist(nr, p.r) < 1e-9 && p.t === "s") { continue; }
        p.l = nl;
        p.r = nr;
        p.t = "s";
        changed++;
    }
    if (changed) { writePath(path, pts, path.closed); }
    return "ok";
}

/*
 * Weld: hold one anchor coincident with another on a different path, optionally
 * with matched tangent direction so the two paths read as one curve across the
 * join. The follower's handles move with its anchor rather than being reset, so
 * the shape of its own curve is preserved.
 *
 * The record lives on the follower - the path the solve actually rewrites -
 * alongside whatever else that path is. An earlier version parked it on a
 * hidden carrier path so that kinds stayed one-per-item; that put an invisible
 * object in the user's layers panel that they would eventually delete without
 * knowing what it was, which is a worse problem than a record with two roles.
 */
function conSolveWeld(reg, entry) {
    var rec = entry.rec;
    var foll = entry;
    var lead = metaGet(reg, metaS(rec, "weldTo", ""));
    if (!lead || !metaAlive(lead) || !metaAlive(foll)) { return "broken"; }

    var li = metaN(rec, "weldTheirs", 0), fi = metaN(rec, "weldMine", 0);
    var lp, fp;
    try { lp = readPath(lead.item); fp = readPath(foll.item); } catch (e) { return "broken"; }
    if (li < 0 || li >= lp.length || fi < 0 || fi >= fp.length) { return "broken"; }

    var L = lp[li], F = fp[fi], moved = false, k;
    var d = vSub(L.a, F.a);
    if (vLen(d) > 1e-9) {
        /*
         * Two useful readings of "keep these together", and they are not the
         * same operation:
         *
         *   shape  - translate the whole follower, so two objects stay locked
         *            in formation. This is what people mean when they say lock
         *            these shapes together.
         *   point  - move only the welded anchor, so the follower stretches to
         *            stay attached. This is what you want for joining the end
         *            of one open path to another.
         */
        if (metaS(rec, "weldMode", "shape") === "point") {
            F.a = vAdd(F.a, d);
            F.l = vAdd(F.l, d);
            F.r = vAdd(F.r, d);
        } else {
            for (k = 0; k < fp.length; k++) {
                fp[k].a = vAdd(fp[k].a, d);
                fp[k].l = vAdd(fp[k].l, d);
                fp[k].r = vAdd(fp[k].r, d);
            }
        }
        moved = true;
    }

    if (metaB(rec, "weldG1", false)) {
        // The leader's live handle at the join sets the direction; the follower
        // opposes it, keeping its own handle lengths.
        var ldir = vSub(L.a, L.l);
        if (vLen(ldir) < 1e-9) { ldir = vSub(L.r, L.a); }
        if (vLen(ldir) > 1e-9) {
            ldir = vNorm(ldir);
            var fl = vDist(F.a, F.l), fr = vDist(F.a, F.r);
            var nl = vSub(F.a, vMul(ldir, fl));
            var nr = vAdd(F.a, vMul(ldir, fr));
            if (vDist(nl, F.l) > 1e-9 || vDist(nr, F.r) > 1e-9) {
                F.l = nl;
                F.r = nr;
                F.t = "s";
                moved = true;
            }
        }
    }
    // Only write when something actually changed. A no-op writePath still
    // perturbs the geometry enough to move the change hash, and the sync loop
    // would then re-solve on every tick forever.
    if (moved) { writePath(foll.item, fp, foll.item.closed); }
    return "ok";
}

