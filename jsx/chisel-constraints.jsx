// 4. The solve pass
//= = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = =

/*
 * Dependency depth, so a tangent circle built on two circles can itself drive
 * another tangent. Depth is computed by walking driver references upward with a
 * hard ceiling, which doubles as the cycle guard: a constraint that reaches
 * MAX_DEPTH is either genuinely that deep or circular, and either way solving
 * it in that order is the best available answer.
 */
function conDepth(reg, entry, seen) {
    if (!seen) { seen = {}; }
    if (seen[entry.id]) { return CON.MAX_DEPTH; }
    seen[entry.id] = true;

    var refs = [entry.rec.a, entry.rec.b, entry.rec.from, entry.rec.weldTo], i, e, d, best = 0;
    for (i = 0; i < refs.length; i++) {
        if (!refs[i]) { continue; }
        e = metaGet(reg, refs[i]);
        if (!e || e.kind === "circle" || e.kind === "ref") { continue; }
        d = 1 + conDepth(reg, e, seen);
        if (d > best) { best = d; }
        if (best >= CON.MAX_DEPTH) { return CON.MAX_DEPTH; }
    }
    return best;
}

function conSortByDepth(reg, entries) {
    var i, j, tmp;
    for (i = 0; i < entries.length; i++) { entries[i].depth = conDepth(reg, entries[i], null); }
    for (i = 1; i < entries.length; i++) {          // insertion sort; ES3, tiny n
        tmp = entries[i];
        j = i - 1;
        while (j >= 0 && entries[j].depth > tmp.depth) { entries[j + 1] = entries[j]; j--; }
        entries[j + 1] = tmp;
    }
    return entries;
}

/*
 * Solve everything. Returns a tally rather than throwing, because one broken
 * constraint in a document of fifty must not stop the other forty-nine from
 * updating.
 */
/*
 * A record can carry more than one role: the same path can be a tangent link,
 * hold tangent locks on its own anchors, and be welded to a neighbour. So the
 * pass runs in three waves rather than switching on a single kind.
 *
 * Order matters. Generated geometry first, because a weld may be attaching to a
 * point that is about to move. Welds next, since they relocate anchors. Tangent
 * locks last, so they get the final word on handle direction.
 */
function conSolveAll(force) {
    var reg = conRegistry(force);
    var gen = [], welds = [], locks = [], i, e, r;
    for (i = 0; i < reg.list.length; i++) {
        e = reg.list[i];
        if (e.kind === "tanlink" || e.kind === "tancircle" || e.kind === "tanline") { gen.push(e); }
        if (e.rec.weldTo) { welds.push(e); }
        if (e.rec.locks) { locks.push(e); }
    }
    conSortByDepth(reg, gen);
    conSortByDepth(reg, welds);

    var okN = 0, broken = 0, impossible = 0;

    function tally(res) {
        if (res === "ok") { okN++; }
        else if (res === "impossible") { impossible++; }
        else { broken++; }
    }

    for (i = 0; i < gen.length; i++) {
        e = gen[i];
        r = "ok";
        try {
            if (e.kind === "tanlink") { r = conSolveLink(reg, e); }
            else if (e.kind === "tancircle") { r = conSolveTanCircle(reg, e); }
            else if (e.kind === "tanline") { r = conSolveTanLine(reg, e); }
        } catch (err) { r = "broken"; }
        tally(r);
    }
    for (i = 0; i < welds.length; i++) {
        try { tally(conSolveWeld(reg, welds[i])); } catch (err2) { tally("broken"); }
    }
    for (i = 0; i < locks.length; i++) {
        try { tally(conSolveG1(locks[i])); } catch (err3) { tally("broken"); }
    }

    return {
        total: gen.length + welds.length + locks.length,
        ok: okN, broken: broken, impossible: impossible, reg: reg
    };
}

