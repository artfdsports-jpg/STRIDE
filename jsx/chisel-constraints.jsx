/*
 * Chisel: constraint graph and solver
 *
 * This is the layer that makes tangency stick. A tangent built here is not a
 * one-off construction that goes stale the moment you nudge a circle; it is a
 * record naming its drivers, and the solver regenerates its geometry from
 * whatever those drivers currently are.
 *
 * Two rules the whole design rests on:
 *
 *   Geometry is truth. Drivers are re-measured from their actual paths every
 *   solve, never read back from stored parameters. So resizing a circle with
 *   the plain selection tool, the scale tool, or Transform Each all work, and
 *   none of them had to know Chisel exists.
 *
 *   Rebuild, never patch. A dependent path is regenerated wholesale from its
 *   drivers. Nudging the existing points toward where they should be is how
 *   parametric systems accumulate drift and eventually produce garbage.
 *
 * Depends on: chisel.jsx, chisel-meta.jsx, chisel-tangency.jsx
 */

var CON = {};

CON.MAX_DEPTH = 8;      // dependency chain limit; also the cycle guard

//= = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = =
// 1. Registry cache
//= = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = = =

/*
 * Scanning every page item is the expensive part, and the panel wants to ask
 * "has anything moved?" several times a second. So the scan is cached and the
 * poll only reads geometricBounds off the items already found - four numbers
 * per constrained object, regardless of how big the document is.
 *
 * The cache is invalidated by any command that creates or destroys a record,
 * and by the document's page item count changing underneath us.
 */
CON.cache = null;

function conInvalidate() { CON.cache = null; }

function conRegistry(force) {
    var doc = app.activeDocument;
    var n = doc.pageItems.length;
    if (!force && CON.cache && CON.cache.doc === doc.name && CON.cache.n === n) {
        return CON.cache.reg;
    }
    var reg = metaScan(doc);
    CON.cache = { doc: doc.name, n: n, reg: reg };
    return reg;
}

/*
 * A cheap fingerprint of everything a constraint could depend on. Bounds are
 * rounded to a thousandth of a point: fine enough that a real nudge always
 * registers, coarse enough that Illustrator's float noise does not make the
 * solver fire on an idle document forever.
 *
 * Digested to a short token rather than returned raw. The panel round-trips
 * this string across the CEP bridge several times a second, so its size is not
 * free; and a raw hash carrying arbitrary punctuation is exactly the kind of
 * thing that collides with whatever separator the reply protocol picked.
 */
function conStateHash(reg) {
    var i, e, b, parts = [];
    for (i = 0; i < reg.list.length; i++) {
        e = reg.list[i];
        if (e.kind !== "circle" && e.kind !== "ref" && e.kind !== "anchor") { continue; }
        try { b = e.item.geometricBounds; } catch (err) { parts.push(e.id + ":gone"); continue; }
        parts.push(e.id + ":" +
            Math.round(b[0] * 1000) + "," + Math.round(b[1] * 1000) + "," +
            Math.round(b[2] * 1000) + "," + Math.round(b[3] * 1000));
    }
    parts.push("n=" + reg.count);
    return conDigest(parts.join("|"));
}

/*
 * Two FNV-1a passes with different seeds, concatenated. A collision means one
 * missed solve, corrected by the next change or by pressing Solve, so 64 bits
 * of a fast non-cryptographic hash is far more than this needs.
 */
function conDigest(s) {
    var h1 = 0x811c9dc5, h2 = 0x01000193, i, c;
    for (i = 0; i < s.length; i++) {
        c = s.charCodeAt(i);
        h1 = h1 ^ c;
        h1 = (h1 * 16777619) >>> 0;
        h2 = h2 ^ (c + i);
        h2 = (h2 * 2166136261) >>> 0;
    }
    return h1.toString(36) + "-" + h2.toString(36);
}

